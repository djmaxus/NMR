function [problem] = genProblem(name,Nx,param,x0)
    %GENPROBLEM Summary of this function goes here
    %   Detailed explanation goes here
    res = @(x,dt) buildResidual(x,dt,param);
    jac = @(x,dt) buildJacobian(x,dt,param);
    problem = struct(...
        'name'    , name,...
        'Nx'      , Nx,...
        'residual', res,...
        'jacobian', jac,...
        'x0'      , x0,...
        'param'   , param...
        );
end

